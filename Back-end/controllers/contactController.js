const deleteContact = async (req, res) => {
    try {

        const contactId = req.params.id;

        const userId = req.user.userId;

        // Get contact first so we know
        // which image belongs to it
        const [contacts] = await pool.query(
            `SELECT image_path
             FROM contacts
             WHERE id = ?
             AND user_id = ?`,
            [
                contactId,
                userId
            ]
        );

        if (contacts.length === 0) {

            return res.status(404).json({
                message: "Contact not found"
            });
        }

        const imagePath =
            contacts[0].image_path;

        // ============================================
        // DELETE DATABASE RECORD
        // ============================================

        await pool.query(
            `DELETE FROM contacts
             WHERE id = ?
             AND user_id = ?`,
            [
                contactId,
                userId
            ]
        );

        // ============================================
        // DELETE IMAGE FILE
        // ============================================

        if (imagePath) {

            const fullImagePath =
                path.join(
                    __dirname,
                    "..",
                    imagePath
                );

            try {

                if (fs.existsSync(fullImagePath)) {

                    fs.unlinkSync(
                        fullImagePath
                    );
                }

            } catch (deleteError) {

                console.error(
                    "Image delete error:",
                    deleteError
                );
            }
        }

        res.status(200).json({
            message: "Contact deleted successfully"
        });

    } catch (error) {

        console.error(
            "Delete Contact Error:",
            error
        );

        res.status(500).json({
            message: "Server error"
        });
    }
};
