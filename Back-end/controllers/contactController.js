const pool = require("../config/db");
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");


// Create Contact
const createContact = async (req, res) => {

    let newUploadedPath = null;
    try {

        console.log("===== CREATE CONTACT CALLED =====");
        console.log("BODY:", req.body);
        console.log("FILE:", req.file);

        const { name, phone, email, address } = req.body;

        // ================================
        // VALIDATION
        // ================================

        if (!name || !phone) {

            if (req.file) {    
                if (req.file && fs.existsSync(req.file.path))
                    fs.unlinkSync(req.file.path);}

            return res.status(400).json({
                message: "Name and phone are required"
            });
        }

        // ================================
        // LOGGED-IN USER ID
        // ================================

        const userId = req.user.userId;

        // ================================
        // TEMPORARY IMAGE + DUPLICATE CHECK
        // ================================

        let imagePath = null;
        let imageHash = null;

        if (req.file) {

            imagePath = req.file.filename;

            // Compute hash of the actual image content
            const fileBuffer = fs.readFileSync(req.file.path);
            imageHash = crypto.createHash("sha256").update(fileBuffer).digest("hex");

            // Check if this exact photo is already used by ANY contact (global check)
            const [duplicateImage] = await pool.query(
                "SELECT id FROM contacts WHERE image_hash = ?",
                [imageHash]
            );

            if (duplicateImage.length > 0) {

                if (fs.existsSync(req.file.path)) {
                    fs.unlinkSync(req.file.path);
                }

                return res.status(409).json({
                    message: "This photo is already used for another contact."
                });
            }
        }

        // ================================
        // INSERT CONTACT
        // ================================

        const [result] = await pool.query(
            `INSERT INTO contacts
            (user_id, name, phone, email, address, image_path, image_hash)
            VALUES (?, ?, ?, ?, ?, ?, ?)`,
            [
                userId,
                name,
                phone,
                email,
                address,
                imagePath,
                imageHash
            ]
        );

        // ================================
        // CONTACT ID GENERATED BY MYSQL
        // ================================

        const contactId = result.insertId;

        console.log("USER ID:", userId);
        console.log("CONTACT ID:", contactId);

        // ================================
        // RENAME IMAGE
        // ================================

        if (req.file) {

            const oldPath = req.file.path;

            const extension = path.extname(
                req.file.originalname
            );

            const finalFileName =
                `${userId}-${contactId}-${path.basename(
                    req.file.originalname,
                    extension
                )}${extension}`;

            newUploadedPath = path.join(
                path.dirname(oldPath),
                finalFileName
            );

            fs.renameSync(
                oldPath,
                newUploadedPath
            );

            // ================================
            // UPDATE IMAGE PATH IN DATABASE
            // ================================

            imagePath = `uploads/${finalFileName}`;

            await pool.query(
                `UPDATE contacts
                 SET image_path = ?
                 WHERE id = ? AND user_id = ?`,
                [
                    imagePath,
                    contactId,
                    userId
                ]
            );

            console.log(
                "FINAL IMAGE NAME:",
                finalFileName
            );
        }

        // ================================
        // RESPONSE
        // ================================

        res.status(201).json({
            message: "Contact created successfully",
            contactId: contactId,
            imagePath: imagePath
        });

    }  catch (error) {
    console.error("Create Contact Error:", error);

    // clean up whichever file actually exists on disk
    const fileToDelete = newUploadedPath || (req.file && req.file.path);
    if (fileToDelete) {
        try {
            if (fs.existsSync(fileToDelete)) fs.unlinkSync(fileToDelete);
        } catch (deleteError) {
            console.error("Image cleanup error:", deleteError);
        }
    }

    // duplicate key (email / image_path unique constraint)
    if (error.code === 'ER_DUP_ENTRY') {
        let field = 'value';
        if (error.sqlMessage.includes('email')) field = 'email';
        else if (error.sqlMessage.includes('image_path')) field = 'image';

        return res.status(409).json({
            message: `This ${field} is already in use.`
        });
    }

    res.status(500).json({ message: "Server error" });
}
};
